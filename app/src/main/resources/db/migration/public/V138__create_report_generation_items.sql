set local lock_timeout = '5s';
set local statement_timeout = '60s';

-- Old jobs retain callbacks_itemized=false. New jobs opt in after the new
-- backend writes their report rows in the same transaction as job creation.
alter table report_generation_jobs
    add column if not exists callbacks_itemized boolean not null default false;

create table if not exists report_generation_items (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    job_id bigint not null,
    exam_id bigint not null,
    report_index integer not null check (report_index >= 0),
    student_id bigint not null,
    status varchar(16) not null check (status in ('PENDING', 'SUCCESS', 'FAILED')),
    file_key varchar(500),
    error_message varchar(1000),
    version bigint not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint report_generation_items_job_index_key
        unique (tenant_id, job_id, report_index),
    constraint report_generation_items_job_exam_tenant_fkey
        foreign key (job_id, exam_id, tenant_id)
        references report_generation_jobs (id, exam_id, tenant_id)
        on delete cascade,
    constraint report_generation_items_tenant_fkey
        foreign key (tenant_id) references tenants(id)
        on delete cascade,
    constraint report_generation_items_state_data_check
        check ((status = 'SUCCESS' and file_key is not null and error_message is null)
            or (status = 'FAILED' and file_key is null and error_message is not null)
            or (status = 'PENDING' and file_key is null and error_message is null))
);

alter table report_generation_items enable row level security;
alter table report_generation_items force row level security;
drop policy if exists tenant_isolation on report_generation_items;
create policy tenant_isolation on report_generation_items
    using (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    with check (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

grant select, insert, update, delete on report_generation_items to lumie_app;
grant usage, select on sequence report_generation_items_id_seq to lumie_app;
